"""Domain-neutral orchestration for the Universal Planning Engine.

The orchestrator coordinates candidate generation, validation, scheduling,
and evaluation. It never executes actions and never imports domain plugins.
"""
from __future__ import annotations

from dataclasses import dataclass, replace
from typing import Mapping, Protocol, Sequence, runtime_checkable

from .contracts import DomainPolicy, PlanningDomainAdapter
from .models import Goal, Plan, PlanStatus, PlanStep, StateSnapshot
from .scheduler import (
    PlanMetrics,
    ScheduleResult,
    evaluate_plan,
    schedule_plan,
)
from .validation import (
    PlanValidationResult,
    PlanningPolicy,
    validate_plan,
)


@runtime_checkable
class PlannerStrategy(Protocol):
    """Injectable candidate-generation strategy."""

    def generate_steps(
        self,
        goal: Goal,
        state: StateSnapshot,
    ) -> Sequence[PlanStep]:
        """Return proposed steps; do not execute them."""


@dataclass(frozen=True)
class PlanningResult:
    """Complete, auditable result of one orchestration attempt."""

    plan: Plan
    validation: PlanValidationResult
    schedule: ScheduleResult | None
    metrics: PlanMetrics | None
    status: PlanStatus
    strategy_name: str

    @property
    def accepted(self) -> bool:
        return self.status in {
            PlanStatus.READY,
            PlanStatus.HUMAN_REVIEW,
        }

    @property
    def requires_human_review(self) -> bool:
        return self.status == PlanStatus.HUMAN_REVIEW


class PlanningOrchestrator:
    """Coordinate planning primitives without owning domain logic."""

    def __init__(
        self,
        *,
        policy: PlanningPolicy | None = None,
        domain_adapter: PlanningDomainAdapter | None = None,
        resource_capacities: Mapping[str, float] | None = None,
        max_parallel_steps: int = 4,
    ) -> None:
        if max_parallel_steps < 1:
            raise ValueError("max_parallel_steps must be at least 1")

        self._policy = policy or PlanningPolicy()
        self._domain_adapter = domain_adapter
        self._resource_capacities = (
            dict(resource_capacities)
            if resource_capacities is not None
            else None
        )
        self._max_parallel_steps = max_parallel_steps

    def _get_domain_policy(self, domain: str) -> DomainPolicy | None:
        if self._domain_adapter is None:
            return None

        domain_policy = self._domain_adapter.get_policy()
        if not isinstance(domain_policy, DomainPolicy):
            raise TypeError("domain adapter must return DomainPolicy")
        if domain_policy.domain_id != domain:
            raise ValueError(
                "domain adapter policy does not match the goal domain"
            )
        return domain_policy

    def plan(
        self,
        goal: Goal,
        state: StateSnapshot,
        strategy: PlannerStrategy,
    ) -> PlanningResult:
        """Generate and assess a plan; never execute its actions."""

        if goal.domain != state.domain:
            raise ValueError("goal domain must match state domain")

        if not isinstance(strategy, PlannerStrategy):
            raise TypeError(
                "strategy must implement generate_steps(goal, state)"
            )

        domain_policy = self._get_domain_policy(goal.domain)
        proposed_steps = strategy.generate_steps(goal, state)

        if isinstance(proposed_steps, (str, bytes)):
            raise TypeError("planner must return a sequence of PlanStep")

        steps = tuple(proposed_steps)
        if not steps:
            raise ValueError("planner returned no steps")
        if not all(isinstance(step, PlanStep) for step in steps):
            raise TypeError("planner returned an invalid step")

        candidate = Plan.create(
            goal,
            state,
            steps,
            rationale="Generated by an injected planning strategy.",
        )

        validation = validate_plan(
            candidate,
            policy=self._policy,
            domain_policy=domain_policy,
        )

        strategy_name = type(strategy).__name__

        if not validation.valid:
            blocked_plan = replace(candidate, status=PlanStatus.BLOCKED)
            return PlanningResult(
                plan=blocked_plan,
                validation=validation,
                schedule=None,
                metrics=None,
                status=PlanStatus.BLOCKED,
                strategy_name=strategy_name,
            )

        validated_plan = replace(candidate, status=PlanStatus.VALIDATED)

        schedule = schedule_plan(
            validated_plan,
            resource_capacities=self._resource_capacities,
            max_parallel_steps=self._max_parallel_steps,
            domain_policy=domain_policy,
        )
        metrics = evaluate_plan(validated_plan, domain_policy=domain_policy)

        if not schedule.feasible:
            final_status = PlanStatus.BLOCKED
        elif any(step.requires_human_approval for step in steps):
            final_status = PlanStatus.HUMAN_REVIEW
        else:
            final_status = PlanStatus.READY

        final_plan = replace(validated_plan, status=final_status)

        return PlanningResult(
            plan=final_plan,
            validation=validation,
            schedule=schedule,
            metrics=metrics,
            status=final_status,
            strategy_name=strategy_name,
        )
